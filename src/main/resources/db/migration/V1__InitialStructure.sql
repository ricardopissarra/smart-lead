ALTER TABLE leads
    ADD CONSTRAINT FK_LEADS_ON_MESSAGE FOREIGN KEY (message_id) REFERENCES messages (message_id);

ALTER TABLE messages
    ADD CONSTRAINT FK_MESSAGES_ON_LEAD_LEAD FOREIGN KEY (lead_lead_id) REFERENCES leads (lead_id);