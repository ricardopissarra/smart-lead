CREATE TABLE leads
(
    lead_id       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title         VARCHAR(255),
    type          VARCHAR(255),
    urgency_level VARCHAR(255),
    description   VARCHAR(255),
    message_id    BIGINT,
    created_at    TIMESTAMP WITHOUT TIME ZONE,
    updated_at    TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_leads PRIMARY KEY (lead_id)
);

CREATE TABLE messages
(
    message_id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    content      OID,
    status       VARCHAR(255),
    lead_lead_id BIGINT,
    created_at   TIMESTAMP WITHOUT TIME ZONE,
    updated_at   TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_messages PRIMARY KEY (message_id)
);

